// Comprueba la integridad del CSV y la búsqueda que utiliza la web.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const XLSX = require('../vendor/xlsx.full.min.js');
const { csvRows, weeksIn, documentLinks, parseCatalog, filterCatalog, sortCatalog } = require('../guides-data.js');
const source = fs.readFileSync(path.join(__dirname, '../data/guias.csv'), 'utf8');
const scope = JSON.parse(fs.readFileSync(path.join(__dirname, '../data/guias-filtro.json'), 'utf8'));
const catalog = parseCatalog(source);
const independent = XLSX.read(source, { type: 'string', raw: true });
const original = XLSX.utils.sheet_to_json(independent.Sheets[independent.SheetNames[0]], { header: 1, raw: true, defval: '' });
assert.equal(scope.criterion, 'DDA');
assert.equal(catalog.length, scope.records);
assert.equal(new Set(catalog.map(g => g.course)).size, scope.courses);
assert.equal(catalog.filter(g => g.links).length, scope.linkedRecords);
assert.equal(catalog.filter(g => !g.links).length, scope.classroomOnlyRecords);
assert.equal(original.length - 1, catalog.length);
for (let i = 0; i < catalog.length; i++) {
  const g = catalog[i];
  assert.deepEqual([g.code, g.course, g.modality, g.week, g.number, g.type, g.sourceLink], original[i + 1].map(value => String(value).trim()));
  if (!g.links) assert.equal(g.sourceLink, 'Disponible en UTP + Class');
  else for (const key of ['original', 'preview', 'download']) assert.equal(new URL(g.links[key]).protocol, 'https:');
}
assert.deepEqual(csvRows('\uFEFFa,b\r\n"coma, y comillas ""dobles""","dos\nlíneas"\r\n'), [['a', 'b'], ['coma, y comillas "dobles"', 'dos\nlíneas']]);
assert.throws(() => csvRows('a,"sin cerrar'), /sin cerrar/);
assert.throws(() => parseCatalog('curso,enlace\nA,B'), /columnas/);
assert.deepEqual(weeksIn('10 a 12'), [10, 11, 12]);
assert.deepEqual(weeksIn('13, 15'), [13, 15]);
assert.deepEqual(weeksIn('5, 14, 17'), [5, 14, 17]);
assert.deepEqual(weeksIn('-'), []);
assert.equal(documentLinks('javascript:alert(1)'), null);
assert.equal(documentLinks('https://user:password@example.org/a'), null);
const drive = documentLinks('https://drive.google.com/file/d/ejemplo_123/view?resourcekey=clave');
assert.equal(new URL(drive.download).searchParams.get('resourcekey'), 'clave');
assert.equal(new URL(drive.preview).pathname, '/file/d/ejemplo_123/preview');
const newton = filterCatalog(catalog, { query: 'fisica newton' });
assert.equal(newton.length, 1);
assert.equal(newton[0].title, 'SEGUNDA LEY DE NEWTON');
assert.equal(filterCatalog(catalog, { query: 'física Newton', modality: 'PRESENCIAL' }).length, 0);
assert.equal(filterCatalog(catalog, { type: 'PPT de ambiente especializado' }).length, 10);
assert.equal(filterCatalog(catalog, { week: 'none' }).length, scope.withoutWeek);
const range = catalog.find(g => g.week === '10 a 12');
assert.ok(filterCatalog(catalog, { week: '11' }).includes(range));
const separate = catalog.find(g => g.week === '13, 15');
assert.ok(!filterCatalog(catalog, { week: '14' }).includes(separate));
const sorted = sortCatalog(catalog, 'week');
assert.equal(sorted[0].weeks[0], 1);
assert.equal(sorted.at(-1).weeks.length, 0);
console.log(`OK: selección por DDA: ${catalog.length} registros, ${scope.courses} cursos, ${scope.linkedRecords} enlaces y ${scope.classroomOnlyRecords} materiales de UTP + Class. Búsqueda, rangos de semanas y enlaces seguros verificados.`);
